def _patient_support(
    *,
    supported: bool,
    evaluator: str | None = None,
    prefilter_path: str | None = None,
    evidence_paths: list[str] | None = None,
    questionnaire_fillable: bool = False,
    block_on_linkage_conflict: bool = True,
    unknown_semantics: str = "unknown_not_false",
) -> dict:
    return {
        "supported": bool(supported),
        "prefilterPath": prefilter_path,
        "evidencePaths": list(evidence_paths or []),
        "evaluator": evaluator,
        "questionnaireFillable": bool(questionnaire_fillable),
        "blockOnLinkageConflict": bool(block_on_linkage_conflict),
        "unknownSemantics": unknown_semantics,
    }


